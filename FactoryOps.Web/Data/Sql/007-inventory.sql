-- Additive inventory ledger and dated replenishment plans. No existing stock is assumed.
SELECT pg_advisory_xact_lock(839472521);

CREATE TABLE IF NOT EXISTS "InventoryStocks" (
    "ProductId" integer PRIMARY KEY REFERENCES "Products" ("Id") ON DELETE RESTRICT,
    "CompanyKey" varchar(64) NOT NULL DEFAULT 'fti-demo' REFERENCES "CompanyProfiles" ("Key") ON DELETE RESTRICT,
    "OnHand" bigint NOT NULL,
    "ReorderPoint" bigint NOT NULL,
    "LeadTimeDays" integer NOT NULL,
    "UpdatedAt" timestamptz NOT NULL,
    CONSTRAINT "CK_InventoryStocks_Values" CHECK ("OnHand" BETWEEN 0 AND 1000000000000 AND "ReorderPoint" BETWEEN 0 AND 1000000000000 AND "LeadTimeDays" BETWEEN 0 AND 3650)
);
CREATE TABLE IF NOT EXISTS "Replenishments" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CompanyKey" varchar(64) NOT NULL DEFAULT 'fti-demo' REFERENCES "CompanyProfiles" ("Key") ON DELETE RESTRICT,
    "ProductId" integer NOT NULL REFERENCES "Products" ("Id") ON DELETE RESTRICT,
    "Quantity" bigint NOT NULL,
    "ExpectedDate" date NOT NULL,
    "Supplier" varchar(200) NOT NULL,
    "Reference" varchar(100) NOT NULL,
    "Notes" varchar(1000) NOT NULL,
    "Status" varchar(16) NOT NULL,
    "ReceivedAt" timestamptz,
    "CreationToken" uuid NOT NULL,
    CONSTRAINT "CK_Replenishments_Values" CHECK ("Quantity" BETWEEN 1 AND 1000000000000 AND "Status" IN ('Planned','Received','Cancelled'))
);
CREATE TABLE IF NOT EXISTS "StockMovements" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CompanyKey" varchar(64) NOT NULL DEFAULT 'fti-demo' REFERENCES "CompanyProfiles" ("Key") ON DELETE RESTRICT,
    "ProductId" integer NOT NULL REFERENCES "Products" ("Id") ON DELETE RESTRICT,
    "Quantity" bigint NOT NULL,
    "Kind" varchar(32) NOT NULL,
    "Reason" varchar(500) NOT NULL,
    "CreatedAt" timestamptz NOT NULL,
    "WorkOrderId" integer REFERENCES "WorkOrders" ("Id") ON DELETE RESTRICT,
    "ReplenishmentId" integer REFERENCES "Replenishments" ("Id") ON DELETE RESTRICT,
    "RequestToken" uuid,
    CONSTRAINT "CK_StockMovements_Nonzero" CHECK ("Quantity" <> 0)
);
CREATE INDEX IF NOT EXISTS "IX_InventoryStocks_CompanyKey" ON "InventoryStocks" ("CompanyKey");
CREATE INDEX IF NOT EXISTS "IX_Replenishments_ProductId" ON "Replenishments" ("ProductId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Replenishments_CompanyKey_CreationToken" ON "Replenishments" ("CompanyKey","CreationToken");
CREATE INDEX IF NOT EXISTS "IX_Replenishments_CompanyKey_ExpectedDate" ON "Replenishments" ("CompanyKey","ExpectedDate");
CREATE INDEX IF NOT EXISTS "IX_StockMovements_CompanyKey_ProductId_CreatedAt" ON "StockMovements" ("CompanyKey","ProductId","CreatedAt");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_StockMovements_CompanyKey_RequestToken" ON "StockMovements" ("CompanyKey","RequestToken");
CREATE INDEX IF NOT EXISTS "IX_StockMovements_WorkOrderId" ON "StockMovements" ("WorkOrderId");
CREATE INDEX IF NOT EXISTS "IX_StockMovements_ReplenishmentId" ON "StockMovements" ("ReplenishmentId");
CREATE INDEX IF NOT EXISTS "IX_StockMovements_ProductId" ON "StockMovements" ("ProductId");
