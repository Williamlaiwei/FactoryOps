"""Rebuild the reviewable SQL and knowledge CSV from the sourced demo manifest."""
import csv
import io
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / "demo/fti-group/catalog.json").read_text(encoding="utf-8"))
quote = lambda value: "'" + str(value).replace("'", "''") + "'"
sql = ['-- Generated by tools/build_demo_pack.py. DEMO codes are not manufacturer SKUs.',
       'SELECT pg_advisory_xact_lock(839472521);',
       'DO $$ BEGIN',
       'IF NOT EXISTS (SELECT 1 FROM "SchemaUpdates" WHERE "Name" = \'004-fti-demo\') THEN']
output = io.StringIO(newline="")
writer = csv.writer(output)
writer.writerow(["Sku", "Name", "Category", "UnitOfMeasure", "Description", "Specifications", "Aliases", "SourceUrl", "DataNotice"])
for product in manifest["products"]:
    values = [product["sku"], product["name"], product["description"], product["category"], product["unit"],
              "", product["specifications"], "", product["source"]]
    sql.append('INSERT INTO "Products" ("CompanyKey","Sku","Name","Description","Category","UnitOfMeasure","Dimensions","Specifications","Packaging","SourceUrl","IsActive","IsDemo","SkuIsVerified") VALUES (\'fti-demo\',' +
               ",".join(map(quote, values)) + ',true,true,false) ON CONFLICT ("CompanyKey","Sku") DO NOTHING;')
    for alias in product["aliases"]:
        sql.append('INSERT INTO "ProductAliases" ("ProductId","Value","NormalizedValue") SELECT "Id",' + quote(alias) + ',' + quote(alias.upper()) +
                   ' FROM "Products" WHERE "CompanyKey"=\'fti-demo\' AND "Sku"=' + quote(product["sku"]) + ' ON CONFLICT DO NOTHING;')
    writer.writerow([product["sku"], product["name"], product["category"], product["unit"], product["description"],
                     product["specifications"], "|".join(product["aliases"]), product["source"], manifest["notice"]])
sql.extend(['INSERT INTO "SchemaUpdates" ("Name") VALUES (\'004-fti-demo\');', 'END IF;', 'END $$;'])
(root / "FactoryOps.Web/Data/Sql/004-fti-demo.sql").write_text("\n".join(sql) + "\n", encoding="utf-8")
(root / "demo/fti-group/knowledge.csv").write_text(output.getvalue(), encoding="utf-8")
print(f"Generated SQL and knowledge CSV for {len(manifest['products'])} demo products.")
